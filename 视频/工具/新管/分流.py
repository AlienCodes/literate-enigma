#!/usr/bin/env python3
"""交付核查输出分流（K112）：哪些 ✘ 只算疑点（片子照出、疑点表跟着发），哪些必须停。做.py 用；快测配样本（做.py 的疑点分支以前从没被真实走过）。
出片后：只有一种算疑点——“自动音频检查”下面每一行都是“响度比全片低”（或“→ 标出的位置必须剪成试听”）。
        削波、电流音、片中停顿过长、程序出错、以后新加的项，一律停（白名单，不是黑名单：K112 前黑名单写“停顿超长”，audio_qc 实际报“片中停顿过长”，对不上）。
出片前：踩坑核查那一步只因“？”不过（文本没有 ✘）已进疑点表，不停；别的 ✘ 一律停。
两处都一样：交付核查返回非 0 却一个 ✘ 也没有（程序崩了）→ 停，不许当成通过。"""

def _块(o, c): return o.split('\n✘ ')[1:] if c else []

def _崩(o, c, 块): return ['交付核查返回 %d 却没有任何 ✘（程序出错）：%s' % (c, ' / '.join(o.strip().splitlines()[-3:])[:300])] if c and not 块 else []

def 出片后(o, c):
    """返回 (疑点行, 停的块)"""
    疑, 停 = [], []
    块 = _块(o, c)
    for b in 块:
        ls = []
        for l in b.split('\n')[1:]:   # 只看标题下面缩进的说明行：块一直延到下一个 ✘，后面的“✔ 响度一致性…”“全部通过”这些顶格行不是这一项的（K112 漏了这一点）
            if l.strip() and l[:1] not in (' ', '\t'): break   # 空行跳过，不当成截止
            if l.strip(): ls.append(l.strip())
        if b.startswith('自动音频检查') and any('响度比全片低' in l for l in ls) and all('响度比全片低' in l or l.startswith('→ 标出的位置必须剪成试听') for l in ls):
            疑 += [l for l in ls if '响度比全片低' in l]
        else: 停.append(b)
    return 疑, 停 + _崩(o, c, 块)

def 出片前(o, c, 文本有错):
    """返回 停的块（踩坑核查只因“？”不过的那一块不停）"""
    块 = _块(o, c)
    return [b for b in 块 if not b.startswith('踩坑核查（') or 文本有错] + _崩(o, c, 块)

def 自检():
    T = '✘ 自动音频检查（削波、电流音、停顿超长、响度骤降）\n    '
    骤 = '108.7–109.3s 响度比全片低 6.0 dB（疑似发闷/变小，需试听）'; 尾 = '\n    → 标出的位置必须剪成试听交用户确认\n✔ 响度一致性'
    f = []
    疑, 停 = 出片后('第30篇 出片后核查：\n' + T + 骤 + 尾, 1)
    if len(疑) != 1 or 停: f.append(f'只有响度骤降应进疑点、不停：疑点 {len(疑)}、停 {len(停)}')
    for 名, 行 in (('骤降+削波', 骤 + '\n    削波：峰值 1.000'), ('片中停顿过长', '片中停顿过长：61.2s 处 1.85s'), ('骤降+片中停顿过长', 骤 + '\n    片中停顿过长：61.2s 处 1.85s'),
                   ('骤降+电流音', 骤 + '\n    4800 Hz 电流音突出 14.2 dB'), ('程序出错', 'audio_qc 返回 1 却没有输出（程序出错）')):
        if not 出片后('x\n' + T + 行 + 尾, 1)[1]: f.append(f'{名} 应停，却没停')
    if not 出片后('Traceback (most recent call last):\n  File x\nKeyError: 1', 1)[1]: f.append('交付核查崩了（返回 1、没有 ✘）应停，却当成通过')
    if 出片后('x\n✔ 全部\n全部通过', 0) != ([], []): f.append('全部通过的误停')
    if not 出片后('x\n✘ 机器复听（逐词读音与脚本一致）：问题数 1\n    S3 x', 1)[1]: f.append('机器复听不过应停')
    if 出片前('x\n✘ 踩坑核查（核查程序自检…）\n    ？ T18\n✔ 数字读法\n【不通过，不得交付】', 1, False): f.append('出片前：踩坑核查只因“？”不过（交付核查返回 1、过滤后没有别的 ✘），不该停（K112b 的“返回非 0 却没有 ✘”会误停这种）')
    if not 出片前('x\n✘ 踩坑核查（…）\n    ✘ T27', 1, True): f.append('出片前：文本有错应停')
    if not 出片前('x\n✘ 读音核对（A23…）\n    待核实 Europe', 1, False): f.append('出片前：读音待核实应停')
    if not 出片前('Traceback\nNameError', 1, False): f.append('出片前：交付核查崩了应停，却当成通过')
    return f

if __name__ == '__main__':
    import sys
    e = 自检(); print('\n'.join(e) or '分流 自检通过（只有响度骤降进疑点；骤降+削波、片中停顿过长、骤降+停顿过长、电流音、程序出错、交付核查崩了都停；出片前 只因“？”不停、文本错/读音/崩了都停）'); sys.exit(1 if e else 0)
